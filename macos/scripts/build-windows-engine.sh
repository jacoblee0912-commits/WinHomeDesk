#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
CMAKE="$ROOT/work/tooling/venv/bin/cmake"
DEP="$ROOT/work/deps-windows/ucrt64"
args=(-S work/FreeRDP -B work/build-windows -G Ninja
  -DCMAKE_TOOLCHAIN_FILE="$ROOT/macos/scripts/windows-toolchain.cmake"
  -DCMAKE_MAKE_PROGRAM="$ROOT/work/tooling/venv/bin/ninja"
  -DCMAKE_BUILD_TYPE=Release -DCMAKE_EXPORT_NO_PACKAGE_REGISTRY=ON
  -DCMAKE_PREFIX_PATH="$DEP" -DOPENSSL_ROOT_DIR="$DEP"
  -DOPENSSL_INCLUDE_DIR="$DEP/include" -DOPENSSL_CRYPTO_LIBRARY="$DEP/lib/libcrypto.dll.a"
  -DOPENSSL_SSL_LIBRARY="$DEP/lib/libssl.dll.a" -DOPENH264_LIBRARY="$DEP/lib/libopenh264.dll.a"
  -DUSE_UNWIND=OFF)
for setting in WITH_SERVER WITH_SHADOW WITH_WINPR_TOOLS BUILD_SHARED_LIBS WITH_OPENH264 WITH_CLIENT_COMMON WITH_CLIENT_CHANNELS CHANNEL_RDPSND_CLIENT; do args+=("-D$setting=ON"); done
for setting in SURFACE_AUDIO_TEST_SOURCE WITH_CLIENT CHANNEL_URBDRC CHANNEL_AUDIN_CLIENT WITH_PLATFORM_SERVER WITH_PROXY WITH_SAMPLE WITH_FFMPEG WITH_MEDIA_FOUNDATION WITH_SWSCALE WITH_JPEG WITH_CUPS WITH_PULSE WITH_ALSA WITH_PCSC WITH_SMARTCARD_EMULATE WITH_MANPAGES WITH_RDTK WITH_WEBVIEW WITH_KRB5 WITH_FUSE WITH_VERBOSE_WINPR_ASSERT WITH_PKCS11 WITH_SSE2 WITH_AVX2 WITH_WINPR_DEPRECATED WITH_FREERDP_DEPRECATED BUILD_TESTING; do args+=("-D$setting=OFF"); done
"$CMAKE" "${args[@]}"
"$CMAKE" --build work/build-windows --target freerdp-shadow-cli --parallel "${BUILD_JOBS:-8}"
